    def run(self):
        end_date = datetime.now()
        start_date = end_date - timedelta(days = 365 * 15)
        # 获取所有报告摘要
        stocks = StockBasicInfo.select(StockBasicInfo.symbol, StockBasicInfo.name).distinct().order_by(StockBasicInfo.symbol.asc()).all()
        symbols = []
        for stock in stocks:

            where = and_(
                FinancialReportBrief.symbol == stock.symbol, 
                FinancialReportBrief.report_time.like("%12-31%"), 
                FinancialReportBrief.report_time >= start_date
            )

            briefs = FinancialReportBrief.select(FinancialReportBrief.return_on_equity, FinancialReportBrief.report_time, FinancialReportBrief.net_profit, FinancialReportBrief.operating_revenue).where(where).order_by(FinancialReportBrief.report_time).all()
            # 净资产收入率又一年低于10%就过滤掉
            skip_stock = False
            for brief in briefs:
                if brief.return_on_equity < 10:
                    skip_stock = True
                    break  # 跳出内层循环

            if skip_stock:
                continue  # 跳过当前 stock，进入下一个 stock
            
            symbols.append(stock.symbol)
        
        print(symbols)

